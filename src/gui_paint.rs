//! layout-paint.json 的绘制代码：面板、固定文字与控件矩形。
//!
//! 由 tools/layout2rs.py 从 JSON 生成，不要手改：改布局就改 JSON 再重新生成。
//! 坐标是面板内的相对坐标（480×270 设计），面板居中由调用方给 x/y。

