/// 底部两个按钮。
pub const BACK: [f32; 4] = [14.5, 213.0, 80.0, 22.0];
pub const CLEAR: [f32; 4] = [104.5, 213.0, 80.0, 22.0];

/// 一个面板内的矩形放到屏幕上。
pub fn at(x: f32, y: f32, rect: [f32; 4]) -> [f32; 4] {
    [x + rect[0], y + rect[1], rect[2], rect[3]]
}

struct Label {
    text: &'static str,
    x: f32,
    y: f32,
    color: u32,
}

const LABELS: [Label; 2] = [
    Label {
        text: "外观 · 绘制",
        x: 14.5,
        y: 10.0,
        color: 0xFFFFFFFF,
    },
    Label {
        text: "画笔",
        x: 261.5,
        y: 36.0,
        color: 0xFFC0C0C0,
    },
];

/// 画面板底和固定文字；画板与色块由调用方按 CANVAS / SWATCHES 画。
pub fn draw(draw: &mut dyn DrawContext, x: f32, y: f32) {
    draw.fill([x, y, PANEL_W, PANEL_H], PANEL_COLOR);
    for label in &LABELS {
        draw.text(label.text, [x + label.x, y + label.y], label.color, false);
    }
}
